#!/usr/bin/env node
/**
 * migrate-presets-to-020.mjs — convert ~/.dsh/.agent-presets/<name>/ presets
 * into kernel 0.2.0 preset declarations.
 *
 * 0.1.5 shipped `dsh-agent-presets` (plural), which DISCOVERED preset
 * directories. 0.2.0 split it into
 *   - `dsh-agent-preset`          one preset = one Loader row whose Config IS the
 *                                 preset definition (id/name/description/order/plugins)
 *   - `dsh-agent-preset-registry` the `agentPresets` Loader-facing service
 * so nothing scans `~/.dsh/.agent-presets` any more. A profile whose
 * `agent-preset-registry.selectedDefault` names an undeclared preset fails every
 * new session with `agent-preset/not-found: Unknown agent preset: <id>`.
 *
 * Relative entry names (`./context-gate.mjs`) are rewritten to absolute paths:
 * once the rows live in the profile patch layer, `./x.mjs` would resolve against
 * the PROFILE directory instead of the preset directory.
 *
 * Usage: node migrate-presets-to-020.mjs <preset-root> <profile-patch.yml> [--dry-run]
 */
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = process.argv[2];
const PATCH = process.argv[3];
const DRY = process.argv.includes('--dry-run');
if (!ROOT || !PATCH) { console.error('usage: node migrate-presets-to-020.mjs <preset-root> <patch.yml> [--dry-run]'); process.exit(2); }

function readPresetMeta(file) {
  if (!existsSync(file)) return {};
  const src = readFileSync(file, 'utf8').replace(/^\uFEFF/, '');
  const meta = {};
  const nm = /^name:\s*(.+)$/m.exec(src);
  if (nm) meta.name = nm[1].trim().replace(/^['"]|['"]$/g, '');
  const od = /^order:\s*(\d+)/m.exec(src);
  if (od) meta.order = Number(od[1]);
  const ds = /^description:\s*>?-?\s*\n((?:\s{2,}.*\n?)+)/m.exec(src);
  if (ds) meta.description = ds[1].split('\n').map((l) => l.trim()).filter(Boolean).join(' ').slice(0, 400);
  else {
    const one = /^description:\s*(.+)$/m.exec(src);
    if (one) meta.description = one[1].trim().replace(/^['"]|['"]$/g, '').slice(0, 400);
  }
  return meta;
}

const quote = (s) => (/^[\w./:@-]+$/.test(s) ? s : `'${String(s).replace(/'/g, "''")}'`);

function indent(src, n) {
  const pad = ' '.repeat(n);
  return src.split('\n').map((l) => (l.trim() === '' ? '' : pad + l)).join('\n');
}

const dirs = readdirSync(ROOT).filter((d) => {
  const p = join(ROOT, d);
  try { return statSync(p).isDirectory() && existsSync(join(p, 'agent.cordis.yml')); } catch { return false; }
}).sort();

const blocks = [];
const report = [];

for (const name of dirs) {
  const dir = join(ROOT, name);
  const body = readFileSync(join(dir, 'agent.cordis.yml'), 'utf8').replace(/^\uFEFF/, '');

  // host-process-entry.js sets `loader.internal = void 0` on the host plane, so
  // the loader falls back to a BARE `import(name)`. A Windows path is not a
  // valid module specifier, so the entry never starts and the preset reports
  // "never started" with ERR_UNSUPPORTED_ESM_URL_SCHEME. file:// URLs are the
  // form dynamic import() accepts.
  //
  // BOTH forms fail the same way and both need rewriting:
  //   name: ./x.mjs              relative to the preset dir under 0.1.5; under
  //                              0.2.0 the rows live in the profile patch layer
  //                              so it would resolve against the PROFILE dir
  //   name: C:/Users/.../x.mjs   already absolute, still not a specifier
  let rewrites = 0;
  const rewritten = body
    .replace(
      /^(\s*(?:- )?id:\s*\S+\s*\n\s*name:\s*)(['"]?)(\.\/[^'"\n]+)\2\s*$/gm,
      (_m, head, q, rel) => {
        rewrites++;
        const abs = resolve(dir, rel).replace(/\\/g, '/');
        return `${head}${q}file:///${abs}${q}`;
      }
    )
    .replace(
      /^(\s*(?:- )?id:\s*\S+\s*\n\s*name:\s*)(['"]?)([A-Za-z]:[\\/][^'"\n]*\.(?:mjs|js|cjs))\2\s*$/gm,
      (_m, head, q, abs) => {
        rewrites++;
        return `${head}${q}file:///${abs.replace(/\\/g, '/')}${q}`;
      }
    );

  const meta = readPresetMeta(join(dir, 'preset.yml'));
  const lines = [];
  lines.push(`    - id: preset-${name}`);
  lines.push(`      name: '@deepseek-ai/dsh-agent-preset'`);
  lines.push('      config:');
  lines.push(`        id: ${name}`);
  if (meta.name) lines.push(`        name: ${quote(meta.name)}`);
  if (meta.description) lines.push(`        description: ${quote(meta.description)}`);
  if (meta.order !== undefined) lines.push(`        order: ${meta.order}`);
  lines.push('        plugins:');
  lines.push(indent(rewritten.replace(/\s+$/, ''), 10));
  blocks.push(lines.join('\n'));
  report.push({ name, entries: (body.match(/^\s*- id:/gm) || []).length, rewrites, order: meta.order });
}

if (!blocks.length) { console.error('no preset directories found under', ROOT); process.exit(1); }

const header = [
  '# ---------------------------------------------------------------------------',
  '# 2026-09-29 kernel 0.2.0 preset declarations (generated by migrate-presets-to-020.mjs).',
  '# 0.1.5 dsh-agent-presets scanned ~/.dsh/.agent-presets; 0.2.0 splits it into',
  '# dsh-agent-preset (one preset = one Loader row) + dsh-agent-preset-registry (the',
  '# service), so nothing scans the directory any more. An undeclared preset fails',
  '# every new session: agent-preset/not-found: Unknown agent preset: <id>',
  '# Relative names (./x.mjs) are rewritten absolute - the rows now live in the',
  '# profile patch layer, where ./x.mjs would resolve against the PROFILE dir.',
  '# Regenerate: node scripts/migrate-presets-to-020.mjs',
  '# ---------------------------------------------------------------------------',
].join('\n');

const END_MARKER = '# END oh-my-whale generated preset declarations';
const addition = `${header}\n- insert:\n${blocks.join('\n')}\n${END_MARKER}\n`;

console.log(`presets found: ${dirs.length}`);
for (const r of report) console.log(`  ${r.name.padEnd(26)} entries=${String(r.entries).padStart(3)} relpaths=${r.rewrites} order=${r.order ?? '-'}`);

if (DRY) { console.log('\n--dry-run: nothing written'); process.exit(0); }

const MARK = '# 2026-09-29 kernel 0.2.0 preset declarations';
const existing = readFileSync(PATCH, 'utf8').replace(/^\uFEFF/, '');
if (existing.includes(MARK)) {
  console.error('\nABORT: the generated block is already present. Remove it first to regenerate.');
  process.exit(1);
}
writeFileSync(PATCH, existing.replace(/\s*$/, '\n') + '\n' + addition, 'utf8');
console.log(`\nappended ${blocks.length} preset declarations to ${PATCH}`);
